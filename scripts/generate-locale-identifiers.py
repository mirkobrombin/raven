#!/usr/bin/env python3
"""Generate native/nt/locale_identifiers.inc: Windows locale identifiers and the locale names Windows gives them.

The pairs come from ICU's table of Windows locale identifiers, icu4c/source/common/locmap.cpp (Unicode-3.0, see
LICENSES/Unicode-3.0.txt), as Chromium's ICU 78.2 carries it at revision d578f2e8b7bd5938e21cfb6bf15c079e0aa5b738 of
https://chromium.googlesource.com/chromium/deps/icu.git. Only the identifier and name of each entry are taken: ICU's underscores become
the hyphens Windows writes, and names that carry a collation keyword or a POSIX variant, which Windows names another way, are left out.
The first name ICU lists for an identifier is the one Windows gives it.

usage: generate-locale-identifiers.py LOCMAP_CPP OUTPUT
"""
import re
import sys
from pathlib import Path

SUBTABLE = re.compile(r"ILCID_POSIX_SUBTABLE\((\w+)\)\s*\{(.*?)\};", re.S)
ENTRY = re.compile(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*\"([^\"]+)\"\s*\}")
ELEMENT = re.compile(r"ILCID_POSIX_ELEMENT_ARRAY\(\s*(0x[0-9a-fA-F]+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)")


def pairs(source):
    found = []
    for _, body in SUBTABLE.findall(source):
        found += [(int(value, 16), name) for value, name in ENTRY.findall(body)]
    found += [(int(value, 16), posix) for value, _, posix in ELEMENT.findall(source)]
    return found


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    seen, rows = set(), []
    for identifier, name in pairs(Path(sys.argv[1]).read_text()):
        if "@" in name or "POSIX" in name or not identifier:
            continue
        name = name.replace("_", "-")
        if name.lower() in seen:
            continue
        seen.add(name.lower())
        rows.append((name, identifier))
    lines = ["// Generated by scripts/generate-locale-identifiers.py from ICU's locmap.cpp (Unicode-3.0). Do not edit.\n",
             "constexpr std::pair<std::u16string_view, uint32_t> generated_locales[]{\n"]
    for start in range(0, len(rows), 6):
        lines.append("\t" + " ".join(f'{{u"{name}", {identifier:#x}}},' for name, identifier in rows[start:start + 6]) + "\n")
    lines.append("};\n")
    Path(sys.argv[2]).write_text("".join(lines))


if __name__ == "__main__":
    main()
