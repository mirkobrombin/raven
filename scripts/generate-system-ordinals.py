#!/usr/bin/env python3
"""Generate native/nt/system_ordinals.inc: the Windows ordinal of every export Raven publishes from libraries programs import by number.

The numbers come from the .spec files of the pinned ReactOS source (the revision provision-controls.py uses), which record the ordinals
Windows gives these libraries. Only names native/nt/system_exports.inc lists are kept, so every entry names an export Raven has.

usage: generate-system-ordinals.py REACTOS_ARCHIVE OUTPUT.inc
"""

from pathlib import Path
import hashlib
import re
import sys
import tarfile

REVISION = "dacf2a6c47fa562799f9c8a41ab6d5c558556558"
ARCHIVE_SHA256 = "5373bbbb60541cb2a49e0acb53360e1218d4f5d56c31f9187b341b9fc16daa69"
LIBRARIES = ("shell32", "oleaut32", "shlwapi", "comctl32", "ws2_32", "wsock32", "wldap32", "activeds", "winspool")
# Libraries whose source is not under dll/win32 in ReactOS.
FOLDERS = {"winspool": "win32ss/printing/base/winspool"}
EXPORTS = Path(__file__).resolve().parent.parent / "native/nt/system_exports.inc"


def published(library):
    text = EXPORTS.read_text()
    found = re.search(rf"{library}_exports\[\]\{{(.*?)\}};", text, re.S)
    return set(re.findall(r'"([^"]+)"', found.group(1))) if found else set()


def ordinals(spec, names):
    result = {}
    for line in spec.splitlines():
        words = line.split("#")[0].split()
        if len(words) < 3 or not words[0].isdigit():
            continue
        rest = [word for word in words[2:] if not word.startswith("-")]
        if not rest:
            continue
        name = rest[0].split("(")[0]
        number = int(words[0])
        if name in names and name not in result.values() and number not in result:
            result[number] = name
    return sorted((name, number) for number, name in result.items())


def main():
    archive, output = Path(sys.argv[1]), Path(sys.argv[2])
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise SystemExit("ReactOS source archive checksum differs")
    lines = ["// Generated by scripts/generate-system-ordinals.py from the .spec files of ReactOS " + REVISION + ".", ""]
    with tarfile.open(archive) as upstream:
        for library in LIBRARIES:
            member = f"reactos-{REVISION}/{FOLDERS.get(library, 'dll/win32/' + library)}/{library}.spec"
            spec = upstream.extractfile(member).read().decode()
            entries = ordinals(spec, published(library))
            lines.append(f"constexpr std::pair<std::string_view, uint16_t> {library}_spec_ordinals[]{{")
            for index in range(0, len(entries), 6):
                lines.append("\t" + " ".join(f'{{"{name}", {number}}},' for name, number in entries[index:index + 6]))
            lines += ["};", ""]
    output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
