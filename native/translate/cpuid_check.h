struct Answer {
	ExitReason reason = ExitReason::none;
	uint32_t eax = 0, ebx = 0, ecx = 0, edx = 0;
};

// mov eax, leaf; mov ecx, subleaf; cpuid (or xgetbv); ret.
inline std::vector<uint8_t> code(uint32_t leaf, uint32_t subleaf, bool xgetbv)
{
	std::vector<uint8_t> bytes = {0xb8};
	for (unsigned i = 0; i < 4; ++i)
		bytes.push_back(static_cast<uint8_t>(leaf >> (8 * i)));
	bytes.push_back(0xb9);
	for (unsigned i = 0; i < 4; ++i)
		bytes.push_back(static_cast<uint8_t>(subleaf >> (8 * i)));
	if (xgetbv)
		bytes.insert(bytes.end(), {0x0f, 0x01, 0xd0});
	else
		bytes.insert(bytes.end(), {0x0f, 0xa2});
	bytes.push_back(0xc3);
	return bytes;
}

// An instruction as clang assembles it.
struct Sample {
	const char *text;
	std::vector<uint8_t> bytes;
};

// A feature bit and instructions that need it: at least one per opcode group the feature adds (every form of FMA3), so the bit may
// be set only when the translator takes every one. The samples it does not take today are printed: that list is the work left
// before the bit can be reported.
struct Feature {
	const char *name;
	uint32_t leaf;
	// 0 eax, 1 ebx, 2 ecx, 3 edx.
	unsigned reg;
	unsigned bit;
	std::vector<Sample> samples;
};

